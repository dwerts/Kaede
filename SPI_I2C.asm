;SPI SUBS
;SEND AND RECEIVE A BYTE FROM SPI. A = BYTE TO SEND, A = RECEIVED BYTE
SPI_TXRX:
	NOP
	PUSH	B
	MOV	B,#8
SPILOOP:
	SETB	SPI_CLK
	SPIWAIT
	RLC	A
	MOV	SPI_OUT,C       ;CLK 1->0: OUTPUT DATA
	CLR	SPI_CLK
	SPIWAIT
	MOV	C,SPI_IN       	;CLK 0->1: READ DATA
	MOV	ACC.0,C
	DJNZ	B,SPILOOP
	SETB	SPI_CLK
	SPIWAIT
	POP	B
	RET



