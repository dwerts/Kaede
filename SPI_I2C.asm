; BINARY COMMANDS (NORMAL MODE) LAND HERE
; most recent rx char in A
BINCHECK:
	CJNE	A,#0FFH,BIN1	;JMP IF NOT RUBOUT
SYNC:	MOV	BYTECOUNT,#0
	JMP	BINFIN
	
; not rubout, so maybe command or params...
; If bit 7 is set, this is the first character of a command,
; which is the command number.  If so, store the command number and
; jump to finish - wait for next characters which complete the command.
BIN1:
	;first byte of command? (bit 7 set only on commands)
	JNB	ACC.7,BDAT	; jump if not the command byte.

	; fall through to here if bit 7 is set - this is a command.
	
	; store the command number
	MOV	CMDNBR,A
	
	; set the byte count to 1
	MOV	BYTECOUNT,#1
	
	; be done for now, wait for next byte.
	JMP	BINFIN

	
	; bit 7 was not set, this is parameters for the command.
	; Increment the byte counter.
BDAT:
	;ASSUME BYTE IS DATA OR CHECKSUM
	PUSH	ACC		;push received char.
	MOV	A,BYTECOUNT	; load bytecount into accumulator. (should be 1 here, could be 0)
	INC	BYTECOUNT	; increments byte count to 2 or higher for commands
	JNZ	BIN2		; jump if Accumulator is not zero
	; accumulator was zero - ERROR: NO COMMAND WAS RECEIVED
	POP	ACC
	JMP	SYNC


	; A holds incremented byte count (1 or 2 or more) here
	; when it holds 1, we got a rubout and are resetting.
	; normally, should hold 2 or more when receiveing commands.
	; MSB of data
BIN2:

	DEC	A			; decrement byte count back
	JNZ	BIN3		; if more than zero, go to next byte...
	
	; first data byte received.
	;MSB DATA RCVD
	POP	ACC
	MOV	CPARAM,A	; store command parameter byte 1
	JMP	BINFIN
	
	; checking for second data byte
BIN3:
	DEC	A
	JNZ	BIN4		; if more than zero, check for next byte
	
	; second data byte received
	;LSB DATA RCVD
	POP	ACC
	MOV	CPARAM+1,A	; store command parameter byte 2
	JMP	BINFIN
	
	
BIN4:
	DEC	A
	JNZ	BIN5		; if not zero here, we have too many chars in the command.
	
	; checksum byte now.
	;CHECKSUM RCVD
	; pop restores checksum char to ACC
	POP	ACC
	
	; now add back the last 3 characters that form the command.
	ADD	A,CMDNBR
	ADD	A,CPARAM
	ADD	A,CPARAM+1
	
	; now logical and with 0x7F
	ANL	A,#07FH
	
	; this should leave us with 0 for good checksums.
	JNZ	SYNC	;JMP IF CHECKSUM ERROR
	
	; fall to here with good command.
	; CMDNBR contains command byte (including makeup bits for param bytes).
	; CPARAM, CPARAM + 1 contain the parameters
	;BINARY COMMAND HAS BEEN RECEIVED
	MOV	A,CMDNBR
	
	; if bit 6 not on, jump to MUP1.
	JNB	ACC.6,MUP1
	
	; bit 6 was on, put the makeup bit back on the first param byte.
	ORL	CPARAM,#80H 	;ADD MAKEUP BIT
	
	; if bit 5 is on, add makeup bit back on the second param byte.
MUP1:
	JNB	ACC.5,MUP2
	ORL	CPARAM+1,#80H 	;ADD MAKEUP BIT
	
	; A holds the command number with makeup bits and command bit.
	; strip off the high 3 bits (command, makup 1, makeup 2);
MUP2:
	; logical and to strip upper 3 bits, leaving command number.
	ANL	A,#1FH	;A = COMMAND NUMBER
	
	; rotate left by 1 bit.
	RL	A		;A = OFFSET INTO JMPTBL
	;EXECUTE COMMAND:
	CPL	DBUG_LED
	setb	numok
	CALL	EXBIN
;if a = 0: bad command. a = 1: good command a = 2: good command, no ack
