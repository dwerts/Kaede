;SHIFT A BYTE LEFT
SHBL	MACRO	BNAM
	MOV	A,BNAM
	RLC	A
	MOV	BNAM,A
	ENDM

;SHIFT A BYTE RIGHT
SHBR	MACRO	BNAM
	MOV	A,BNAM
	RRC	A
	MOV	BNAM,A
	ENDM

;SHIFT BYTE STRING LEFT. CLEAR C BEFORE CALLING.REG IS LEAST SIG BYTE, NBR IS NUMBER OF BYTES.
SBSL	MACRO  REG,	NBR
	SHBL	REG
	IF (NBR > 1)
	 SBSL REG-1,NBR-1
	ENDIF
	ENDM

;SHIFT BYTE STRING RIGHT. CLEAR C BEFORE CALLING.REG IS MOST SIG BYTE, NBR IS NUMBER OF BYTES.
SBSR	MACRO  REG,	NBR
	SHBR	REG
	IF (NBR > 1)
	 SBSR REG+1,NBR-1
	ENDIF
	ENDM

;SHIFT FAC1 MANTISSA LIFT 1 BIT (MULTIPLY BY 2)
