	clr	ri          ;clear rcv interrupt flag
	JNB	BINCOM,ASCC	;JMP IF ASCII COMMUNICATIONS
	;BINARY COMMUNICATIONS
	CALL	BINCHECK
	JMP	UFIN
	
; ASCII COMMUNICATIONS - DEPRECATED
	;save character in buffer
