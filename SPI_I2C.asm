;a = chan # (0 to 3)
;return with jog and jdir set according to value of selected analog chan
jscheck:
	rl	a
	inc	a
	mov	r2,a
	clr	jog
	clr	jdir
	add	a,#xj
	mov	r0,a		;r0 points to lsb of chan rdg
	mov	a,#xb
	add	a,r2
	mov	r1,a		;r1 points to lsb of chan base
	clr	c
	CRON
	mov	a,@r0
	subb	a,@r1
	dec	r0
	dec	r1
	mov	b,a		;b = lsb of difference
	mov	a,@r0
	CROF
	subb	a,@r1
	jb	acc.7,js1	;jmp if a.b is negative
	;a.b is positive
	clr	c
	xch	a,b
	subb	a,dband+1
	xch	a,b
	subb	a,dband		;a.b = val - dband
	jb	acc.7,jsret
	setb	jog
	jmp	jsret
js1:	;a.b is negative
	xch	a,b
	add	a,dband+1
	xch	a,b
	addc	a,dband		;a.b = val + dband
	jnb	acc.7,jsret
	setb	jog
	setb	jdir		;reverse signs
jsret:	ret

zskip:
sk00:
	clr	a
	movc	a,@a+dptr
	jnz	sk01
	jmp	sk02
sk01:	inc	dptr
	jmp	sk00
sk02:	inc	dptr
	inc	r6
	ret

;search for match between char string in cmdbuf and cmdtbl. length of string is in r3.
ismatch:
	mov	r6,#0	;command position counter
	mov	dptr,#cmdtbl
im00:
	mov	r0,#cmdbuf
	mov	a,r3	;string length
	mov	r5,a
im03:
	clr	a
	movc	a,@a+dptr
	jnz	im04
	inc	dptr
	inc	r6
	jmp	im05
im04:
	clr	c
	subb	a,@r0
	jnz	im01
	;chars match
	djnz	r5,im02
	jmp	match
im02:
	inc	r0
	inc	dptr
	jmp	im03
im01:
	call	zskip
im05:
	movc	a,@a+dptr
	jnz	im00
	;end of command table
nomatch:
        clr	a
;        call	cmd_init
        jmp	imrt
match:
	inc	dptr
	clr	a
	movc	a,@a+dptr
	jnz	nomatch
        REFRESH              ; refresh watchdog timer
	;2*r6 is offset into jmptbl:
	mov	a,r6
	add	a,r6
	mov	r0,a
	mov	dptr,#jmptbl
	movc	a,@a+dptr       ;high byte of addrs
	mov	r1,a
	mov	a,r0
	inc	a
	movc	a,@a+dptr       ;low byte of address
	mov	cptrl,a
	MOV	cptrh,r1
;	setb	cmd_rdy
	mov	dpl,a
	mov	dph,r1
	clr	a
	jmp	@a+dptr		;jump to command procedure
imrt:
	ret

;initialize command decoder (register bank 2)
cmd_init:
	mov	r3,#0	;command char count
	clr	numok
	clr	cmdrcvd
	clr	cmderr
	clr	cmd_rdy
	mov	cbufptr,#cmdbuf
	mov	rxptr,#rxbuf	;UART receive buffer
	mov	r0,#cparam
	mov	r1,#MSIZ
z00:	mov	@r0,#0
	inc	r0
	djnz	r1,z00
	ret

;a = received char
process_char:
	;decide what to do with char:
	cjne	a,#0dh,pcctnu
	jmp	eocmd
eocmd:  ;end of line
	clr	a
	jb	cmdrcvd,excmd	;jmp if command entered
	cjne	r3,#0,excmd	;in case command does not need parameter
	jmp 	pcfin           ;extra end of line: ignore
        jb	cmderr,pcq
excmd:	call	ismatch		;this will set up cptrh.cptrl
;if a = 0: bad command. a = 1: good command
pcq:
	jnz	pcb
	mov	A,#'0'         ;BAD
	jmp	pcp
pcb:	cjne	a,#2,pcg
    	jmp	pcig
pcg:	MOV     A,#'1'		;GOOD
;	CPL	DBUG_LED
	MOV	UTMOUT,#UCOUNT	;RESET UART TIMEOUT COUNT
pcp:    CALL    SENDCHAR
	MOV	DPTR,#SEPARATOR
	CALL	SENDSTRING
pcig:	call	cmd_init
	jmp	pcfin
pcctnu:
	jb	cmdrcvd,pc01	;jump if command has been received
	;complete command not received yet
	;delimiter?
	cjne	a,#' ',pc001
	jmp	isdelim
pc001:	cjne	a,#',',pc002
	jmp	isdelim
pc002:	cjne	a,#'=',pc003
	jmp	isdelim
pc003:	cjne	a,#09h,pc004    ;tab
isdelim:
	cjne	r3,#0,pc005
	jmp	numerr		;no command has been entered
pc005:	setb	cmdrcvd         ;mark command as being received
	jmp	pcfin
pc004:
	;must be alphabetic:
	;upper case:
ucck:	JALT	'A',numerr
	JAGT	'Z',cklc
	;upper case. convert to lower case
	orl	a,#020h
cklc:	JALT	'a',numerr
	JAGT	'z',numerr
	;alphabetic char. put in buffer
	mov	r0,cbufptr
	cjne	r0,#cmdbuf+CMDSIZ,pc00  ;jmp if buffer not full
	;buffer full
	jmp	numerr
pc00:	mov	@r0,a
	inc	r3	;increment char count
	inc	r0
	mov	cbufptr,r0
	jmp pcfin
pc01:
	;must be a number
	JNB	USEHEX,PC01A
	;HEX
	CALL	ASCII2HEX
	JC	numerr
	JMP	PC01B
PC01A:
	JALT	'0',numerr
	JAGT	'9',numerr
PC01B:
	;char is numeric
	anl	a,#0fh
	setb	numok		;set the numeric bit
	;decimal to hex conversion:
	push	acc
	JB	USEHEX,PC01C
	FACX10	cparam+MSIZ-1,cparamb+MSIZ-1		;multiply cparam by 10
	JMP	PC01D
PC01C:	MOV	R1,#CPARAM
	CALL	MMUL16			;MULTIPLY CPARAM BY 16
PC01D:
	;add digit to cparam:
	mov	r0,#cparam+MSIZ-1
	mov	r1,#MSIZ
	pop	acc
	clr	c
pc02:	addc	a,@r0
	mov	@r0,a
	clr	a
	dec	r0
	djnz	r1,pc02
        jmp	pcfin
numerr:
	setb	cmderr
pcfin:
	ret

process_buf:
	mov	rxptr,#rxbuf
pb1:
	mov	r0,rxptr
	mov	a,@r0
	cjne	a,#0dh,pb2	;jmp if char is not cr
	;char is cr: end of command
	call	process_char
	ret
pb2:
	call	process_char
	inc	rxptr
	jmp	pb1
;end of process_buf

OUTNUM:
	JB	USEHEX,PNTHEX
	CALL	OUT5
	RET
PNTHEX:	CALL	OUT4H
	RET

