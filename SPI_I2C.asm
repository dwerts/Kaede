;UART interrupt - characters are received here...
UARTINT:
	jnb	ri,uartend	;jump if not RI (receive interrupt) bit set. (ignore tx interrupt)
	PUSH	B		; push register B (Multiplication register)
	push	acc		; push accumulator
	push	psw		; push program status word
	mov	psw,#010h	;select register bank 2
	
; character received gets us here,
; or receive interrupt active when we get to the end of this stuff...
