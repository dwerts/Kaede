RECBYTE:        ; waits for a single character to be received
                ; by the UART.  places this character into A.
        IF (DEBUG=0)
        JNB     RI,$
        MOV     A,SBUF
        CLR     RI
        ENDIF
        RET

SENDBYTE:       ; sends value contained in A to UART
	IF (DEBUG=0)
        JNB     TI,$            ; wait until present char gone
        CLR     TI              ; must clear TI
        MOV     SBUF,A
        ENDIF
        RET


SEND_ID:
	MOV	DPTR,#ID_STRING
	MOV	R0,#25
SID1:
	CLR	A
	MOVC	A,@A + DPTR
	INC	DPTR
	CALL	SENDBYTE
	DJNZ	R0,SID1
	RET

